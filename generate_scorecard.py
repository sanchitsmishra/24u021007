    # 1. MSR-VTT Benchmark Metrics Bar Chart
    msr = data.get("msrvtt", {})
    if msr and msr.get("scores"):
        scores = msr.get("scores", {})
        fig, ax = plt.subplots(figsize=(7.2, 2.7), dpi=300)
        metric_names = ["BLEU-1", "BLEU-2", "BLEU-3", "BLEU-4", "METEOR", "ROUGE-L"]
        metric_values = [scores.get(m, 0.0) for m in metric_names]
        bar_colors = ["#3B82F6", "#60A5FA", "#93C5FD", "#BFDBFE", "#10B981", "#8B5CF6"]

        bars = ax.bar(metric_names, metric_values, color=bar_colors, width=0.52, edgecolor="#1E293B", linewidth=0.6, zorder=3)
        ax.set_ylabel("Score (%)", fontsize=8.5, fontweight="bold", color="#334155")
        ax.set_title(f"MSR-VTT 1k-Test Benchmark Metric Overview ({msr.get('total_samples', 1000):,} Clips)", fontsize=10.5, fontweight="bold", color="#0F172A", pad=10)
        max_val = max(metric_values) if metric_values else 30
        ax.set_ylim(0, max(max_val * 1.25, 10.0))
        ax.grid(axis="y", linestyle="--", alpha=0.4, zorder=0)
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        ax.spines["left"].set_color("#CBD5E1")
        ax.spines["bottom"].set_color("#CBD5E1")
        ax.tick_params(colors="#475569", labelsize=8)

        for bar in bars:
            h = bar.get_height()
            ax.annotate(f"{h:.2f}%", xy=(bar.get_x() + bar.get_width() / 2, h), xytext=(0, 3), textcoords="offset points", ha="center", va="bottom", fontsize=8, fontweight="bold", color="#1E293B")

        plt.tight_layout()
        chart1_path = output_dir / "chart_metrics_overview.png"
        plt.savefig(chart1_path, dpi=300, bbox_inches="tight")
        plt.close()
        chart_paths["metrics_bar"] = chart1_path

    # 2. Per-sample Metrics & Latency Dual Comparison (MSR-VTT)
    details = msr.get("details", [])
    if details:
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(7.2, 2.6), dpi=300)
        chart_details = details[:20] if len(details) > 20 else details
        sample_ids = [d["video_id"].replace("video", "v") for d in chart_details]
        rouge_scores = [d["metrics"].get("ROUGE-L", 0.0) for d in chart_details]
        meteor_scores = [d["metrics"].get("METEOR", 0.0) for d in chart_details]
        latencies = [d.get("latency_seconds", 0.0) for d in chart_details]

        x = np.arange(len(sample_ids))
        w = 0.38
        ax1.bar(x - w / 2, rouge_scores, width=w, label="ROUGE-L", color="#8B5CF6", edgecolor="#1E293B", linewidth=0.5, zorder=3)
        ax1.bar(x + w / 2, meteor_scores, width=w, label="METEOR", color="#10B981", edgecolor="#1E293B", linewidth=0.5, zorder=3)
        ax1.set_xticks(x)
        ax1.set_xticklabels(sample_ids, rotation=45, ha="right", fontsize=7, color="#475569")
        ax1.set_ylabel("Score (%)", fontsize=8, fontweight="bold", color="#334155")
        ax1.set_title("Qualitative Scores (Representative Clips)", fontsize=9, fontweight="bold", color="#0F172A")
        ax1.legend(frameon=True, fontsize=7, loc="upper right")
        ax1.grid(axis="y", linestyle="--", alpha=0.35, zorder=0)
        ax1.spines["top"].set_visible(False)
        ax1.spines["right"].set_visible(False)
        ax1.spines["left"].set_color("#CBD5E1")
        ax1.spines["bottom"].set_color("#CBD5E1")

        all_lats = [d.get("latency_seconds", 0.0) for d in details]
        avg_lat = sum(all_lats) / len(all_lats) if all_lats else 0.0
        ax2.plot(x, latencies, marker="o", color="#F59E0B", linewidth=1.8, markersize=4.5, zorder=3, label="Latency (s)")
        ax2.axhline(avg_lat, color="#DC2626", linestyle=":", linewidth=1.2, label=f"Avg ({avg_lat:.2f}s)")
