def main():
    parser = argparse.ArgumentParser(description="Generate PDF and HTML Scorecards from Evaluation Results")
    parser.add_argument(
        "--report",
        type=str,
        default="results/evaluation_report.json",
        help="Path to evaluation_report.json",
    )
    parser.add_argument(
        "--output_dir",
        type=str,
        default="results",
        help="Directory to save generated scorecards",
    )
    args = parser.parse_args()

    report_path = Path(args.report)
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    if not report_path.exists():
        print(f"[-] Report not found at: {report_path}")
        sys.exit(1)

    with open(report_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    # 1. Generate publication-grade charts and report
    from generate_evaluation_report import (
        generate_publication_charts,
        build_evaluation_report_pdf,
    )
    chart_paths = generate_publication_charts(data, out_dir / "charts")

    # 2. Build Publication-Grade PDF Report
    pdf_path = out_dir / "evaluation_report.pdf"
    build_evaluation_report_pdf(data, chart_paths, pdf_path)

    # 3. Build HTML Scorecard
    html_path = out_dir / "evaluation_scorecard.html"
    build_html_scorecard(data, html_path)

    print("\n" + "=" * 60)
    print("      EVALUATION REPORT & SCORECARD GENERATION COMPLETE          ")
    print("=" * 60)
    print(f"  [PDF]  Evaluation Report : {pdf_path.resolve()}")
    print(f"  [HTML] Scorecard         : {html_path.resolve()}")
    print("=" * 60 + "\n")


if __name__ == "__main__":
    main()
